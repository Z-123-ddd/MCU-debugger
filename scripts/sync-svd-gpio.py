#!/usr/bin/env python3
"""Record where each SVD's GPIO ports live, so a part can be identified without
a DEV_ID table.

Why
---
No vendor file maps DEV_ID -> part: the CMSIS-Pack `.pdsc` has only
description/memory/algorithm/debug, the SVDs never mention it, and SEGGER's
`JlinkDevices.xml` carries Name/Core/WorkRAM/Flash but no ID either. So a new
model cannot be looked up -- it has to be *measured*.

What makes measuring possible: each family puts its GPIO blocks at a distinct
base address. Probing a couple of addresses tells the family apart long before
any part number is known:

    N32G05x/G432/G435/G451..457   0x40010800
    N32G41x                       0x40021400
    N32G401                       0x40023400
    N32H473..H499                 0x4002C000
    N32H7xx                       0x58032800

Combined with the flash size and the set of GPIO ports that answer, that is
enough to land on a part with no database entry. This script pre-computes the
addresses (and the port list) per SVD into `data/svd_gpio.json`.

Usage
-----
    python scripts/sync-svd-gpio.py            # all SVDs under svd/
    python scripts/sync-svd-gpio.py --dry-run
"""

from __future__ import annotations

import argparse
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "data" / "svd_gpio.json"

PERIPHERAL_RE = re.compile(r"<peripheral[^>]*>(.*?)</peripheral>", re.S)
NAME_RE = re.compile(r"<name>(GPIO[A-H])</name>")
BASE_RE = re.compile(r"<baseAddress>(0x[0-9A-Fa-f]+)</baseAddress>")


def scan_svd(path: pathlib.Path) -> dict | None:
    text = path.read_text(encoding="utf-8", errors="ignore")
    ports: list[tuple[int, str]] = []
    for block in PERIPHERAL_RE.findall(text):
        name = NAME_RE.search(block)
        base = BASE_RE.search(block)
        if not name or not base:
            continue
        ports.append((int(base.group(1), 16), name.group(1)))
    if not ports:
        return None
    ports.sort()
    return {
        # The lowest GPIO address is the discriminator used at runtime.
        "gpioBase": f"0x{ports[0][0]:08X}",
        "portCount": len(ports),
        "ports": [name for _, name in ports],
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()

    entries: dict[str, dict] = {}
    for svd in sorted((ROOT / "svd").glob("**/*.svd")):
        info = scan_svd(svd)
        if info:
            entries[svd.name] = info

    if not entries:
        print("[ERROR] no SVD with GPIO peripherals found under svd/", file=sys.stderr)
        return 1

    # Group by base so the runtime can answer "which families live here".
    by_base: dict[str, list[str]] = {}
    for name, info in entries.items():
        by_base.setdefault(info["gpioBase"], []).append(name)
    for names in by_base.values():
        names.sort()

    print(f"[OK] {len(entries)} SVD, {len(by_base)} distinct GPIO base addresses")
    for base, names in sorted(by_base.items()):
        print(f"     {base}  {', '.join(names)}")

    payload = {
        "comment": ("Where each SVD puts its GPIO blocks. Used to identify a part "
                    "without a DEV_ID table: the base address names the family, the "
                    "flash size names the density, the ports that answer name the "
                    "package. Generated by scripts/sync-svd-gpio.py."),
        "byBase": {k: v for k, v in sorted(by_base.items())},
        "svd": dict(sorted(entries.items())),
    }

    if args.dry_run:
        print(f"[dry-run] would write {OUT}")
        return 0
    OUT.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"[OK] wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
