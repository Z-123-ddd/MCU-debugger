#!/usr/bin/env python3
"""Harvest the device names SEGGER ships inside JLinkARM.dll.

Why
---
J-Flash and JLinkGDBServer do support these parts, but the names in SEGGER's
device database are spelled **without** the order-code suffix:

    -device N32G455CC      works
    -device N32G455CCL7    "Failed to get index for device name"

So the tool must translate an order code into SEGGER's spelling before handing it
to J-Link, and it can only do that reliably if it knows which names exist. There is
no published list; the names are plain strings inside `JLinkARM.dll`.

This script extracts them (plus any `JLinkDevices.xml` drop-ins) into
`data/jlink_devices.json`, which the app reads at runtime.

Usage
-----
    python scripts/sync-jlink-devices.py                 # scan installed J-Link
    python scripts/sync-jlink-devices.py --dll <path>
    python scripts/sync-jlink-devices.py --dry-run
"""

from __future__ import annotations

import argparse
import glob
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "data" / "jlink_devices.json"

#: J-Link install roots to look at, newest version first.
DLL_GLOBS = [
    r"C:/Program Files/SEGGER/JLink*/JLinkARM.dll",
    r"C:/Program Files (x86)/SEGGER/JLink*/JLinkARM.dll",
]

#: A device name starts with the vendor prefix and is upper-case alnum only.
NAME_RE = re.compile(rb"\x00(N32[A-Z][A-Z0-9]{3,14})\x00")


def scan_dll(path: pathlib.Path) -> set[str]:
    data = path.read_bytes()
    names: set[str] = set()
    for match in NAME_RE.finditer(data):
        names.add(match.group(1).decode("ascii"))
    return names


def scan_devices_xml() -> dict[str, str]:
    """SEGGER lets vendors drop extra devices into JLinkDevices.xml."""
    found: dict[str, str] = {}
    # Vendor drop-ins live here and are the authoritative list: measured on this
    # machine, `%APPDATA%/SEGGER/JlinkDevices/Nations-JLinkDevices.xml` carries 197
    # ChipInfo entries (incl. N32H473CC) while JLinkARM.dll only has 124 older
    # names. Scanning the DLL alone made N32H473 look unsupported when it is not.
    patterns = [
        str(pathlib.Path.home() / "AppData/Roaming/SEGGER/JlinkDevices/*.xml"),
        str(pathlib.Path.home() / "AppData/Roaming/SEGGER/JlinkDevices/Devices/*.xml"),
        str(pathlib.Path.home() / "AppData/Roaming/SEGGER/JlinkDevices/Devices/*/*.xml"),
        r"C:/Program Files/SEGGER/JLink*/JLinkDevices.xml",
        r"C:/Program Files/SEGGER/JLink*/Devices/*/*.xml",
        r"C:/Program Files (x86)/SEGGER/JLink*/JLinkDevices.xml",
    ]
    for pattern in patterns:
        for path in glob.glob(pattern):
            try:
                text = pathlib.Path(path).read_text(encoding="utf-8", errors="ignore")
            except OSError:
                continue
            for match in re.finditer(r'<ChipInfo\s+[^>]*Name="([^"]+)"', text):
                found[match.group(1)] = path
    return found


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--dll", help="explicit JLinkARM.dll path")
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()

    dlls = [args.dll] if args.dll else [p for g in DLL_GLOBS for p in glob.glob(g)]
    if not dlls:
        print("[ERROR] JLinkARM.dll not found; pass --dll", file=sys.stderr)
        return 1

    names: set[str] = set()
    sources: list[str] = []
    for dll in dlls:
        path = pathlib.Path(dll)
        if not path.exists():
            continue
        found = scan_dll(path)
        if found:
            names |= found
            sources.append(f"{path} ({len(found)} names)")
    extra = scan_devices_xml()
    names |= set(extra)
    if extra:
        sources.append(f"JLinkDevices.xml ({len(extra)} names)")

    if not names:
        print("[ERROR] no device names extracted", file=sys.stderr)
        return 1

    # Group by family so the app can answer "does SEGGER know N32G455 at all".
    families: dict[str, list[str]] = {}
    for name in sorted(names):
        match = re.match(r"^(N32[A-Z]+[0-9]+)", name)
        if not match:
            continue
        families.setdefault(match.group(1), []).append(name)

    payload = {
        "comment": ("Device names SEGGER ships inside JLinkARM.dll. Order codes keep a "
                    "suffix (N32G455CCL7) that J-Link does not accept; the names here are "
                    "the accepted spelling. Generated by scripts/sync-jlink-devices.py."),
        "sources": sources,
        "families": {k: v for k, v in sorted(families.items())},
        "devices": sorted(names),
    }

    print(f"[OK] {len(names)} device names, {len(families)} families")
    for line in sources:
        print(f"     from {line}")
    sample = [n for n in payload["devices"] if n.startswith("N32G455")]
    print(f"     N32G455: {', '.join(sample)}")

    if args.dry_run:
        print(f"[dry-run] would write {OUT}")
        return 0
    OUT.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"[OK] wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
