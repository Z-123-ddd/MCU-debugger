#pragma once

#include <QHash>
#include <QString>
#include <QStringList>

namespace mrd {

/// Per-part facts taken from the vendor CMSIS-Pack (`data/parts.json`).
///
/// `data/device_ids.json` is keyed by DBGMCU DEV_ID and therefore only knows
/// families (`N32H473`): one DEV_ID is shared by every package and flash size.
/// The pack describes each exact part (`N32H473CE`) instead, which is where the
/// real answers live:
///
///  * `flashBytes` / `ramBytes`  from the linker `<memory>` rows,
///  * `capabilities`             how many SPI/ADC/DMA/... this model has,
///  * `package` / `ioCount`      the package and its bonded IO count.
///
/// The table is generated by `scripts/sync-part-table.py`; `data/` ships with the
/// app, while the packs themselves are not committed.
class PartTable
{
public:
    struct Entry
    {
        QString part;
        QString pack;
        QString package;    ///< "UQFN48/LQFP48"
        QString svd;        ///< relative SVD path the pack assigned
        QString sram;       ///< "160KB" prose figure, when the pack states it
        QString ccmSram;    ///< "32KB"
        QString backupSram; ///< "4KB"
        QString flash;      ///< "512KB" prose figure
        QString clock;      ///< "200MHz"
        int flashBytes = 0;
        int ramBytes = 0;   ///< IRAM1 size (core SRAM + CCM, as the linker sees it)
        int ioCount = 0;
        QHash<QString, int> capabilities;
        bool valid = false;
    };

    /// Load `data/parts.json` (idempotent). Returns the number of parts.
    static int load(QString *error = nullptr);
    static bool loaded();
    static int count();
    static QString sourcePath();

    /// Exact match first, then the longest table entry that prefixes \a partName
    /// ("N32H473CEU7" -> "N32H473CE"). Returns an invalid entry when nothing fits.
    static Entry lookup(const QString &partName);

    /// All known part names whose name starts with \a stem (for diagnostics).
    static QStringList matching(const QString &stem);

    /// "512 KB" / "1.5 MB" — sizes as the UI shows them.
    static QString formatSize(int bytes);

    /// "Flash 512 KB  /  RAM 192 KB"; empty when both sizes are unknown.
    ///
    /// Kept here (not in the widget) so the exact wording the status bar shows is
    /// covered by the self-test.
    static QString memorySummary(int flashBytes, int ramBytes);
};

} // namespace mrd
